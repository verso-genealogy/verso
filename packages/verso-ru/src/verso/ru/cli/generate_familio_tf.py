"""Generate `familio_*.tf` for a village's blood-relatives.

A second, separate publishing target alongside the geni generator: this runs the
SAME DSL→domain translation (`verso.ru.pipeline.translate.translate_village`, including
consolidation, through the facts loader `consolidated_facts`), then projects only
the curated kin subset onto the narrow `dmalch/familio` provider schema
(`verso.ru.familio`). Event comments cite each person's records — found through the
facts bridge, with the about section the translator minted for each.

Kin are listed in `<village>/familio_kin.py` as a `KIN` mapping of canonical geni
res_name → familio person UUID (or None to create). Output (default
`<village>/terraform/familio/`):
    familio_persons.tf    — one familio_person per kin entry (+ parents links)
    familio_marriages.tf  — a familio_marriage per kin-kin union
    familio_imports.tf    — import{} blocks adopting existing familio persons

Usage:
    python -m verso.ru.cli.generate_familio_tf --village "Нижняя Яичница"
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

from verso.ru.facts.projection import consolidated_identity
from verso.ru.familio.model import FamilioSource
from verso.ru.familio.projection import parse_sources, project_kin, settlement_locals_hcl
from verso.ru.familio.sources import appearances_by_canonical
from verso.ru.pipeline.facts import consolidated_facts


def load_kin(
    village_dir: Path,
) -> tuple[
    dict[str, str | None],
    dict[str, tuple[str, ...]],
    dict[str, tuple[FamilioSource, ...]],
]:
    """Load `KIN` (required) and the optional `PARENT_OVERRIDES` / `FAMILIO_SOURCES`
    mappings from `<village>/familio_kin.py`. Errors loudly if the file or `KIN`
    is missing — there is no implicit 'everyone' fallback, by design (familio gets
    blood-relatives only). `PARENT_OVERRIDES` (canonical res_name → tuple of parent
    res_names) pins parentage the census models imprecisely. `FAMILIO_SOURCES`
    (res_name → list of citation dicts) lists each person's «Источники»; both
    default to empty."""
    kin_path = village_dir / "familio_kin.py"
    if not kin_path.exists():
        raise FileNotFoundError(
            f"no kin registry at {kin_path}. Create it with a `KIN` dict "
            "mapping canonical geni res_name → familio UUID (or None)."
        )
    spec = importlib.util.spec_from_file_location(
        f"familio_kin_{village_dir.name}", str(kin_path))
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load kin registry {kin_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    kin = getattr(module, "KIN", None)
    if not isinstance(kin, dict):
        raise TypeError(f"{kin_path} must define a `KIN` dict")
    overrides = getattr(module, "PARENT_OVERRIDES", {}) or {}
    sources = parse_sources(getattr(module, "FAMILIO_SOURCES", {}) or {})
    return kin, overrides, sources


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--village", required=True)
    parser.add_argument(
        "--output-dir",
        help="Where to write familio_*.tf (default <village>/terraform/familio).",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Fail if any DSL file failed to import (its records — and any kin "
             "among them — would be silently missing from the projection).",
    )
    args = parser.parse_args(argv)

    village_dir = Path(args.village)
    output_dir = Path(args.output_dir) if args.output_dir else village_dir / "terraform" / "familio"
    output_dir.mkdir(parents=True, exist_ok=True)

    kin, parent_overrides, sources_by_res = load_kin(village_dir)

    # Full DSL→domain translation (shared with the geni generator) and the
    # assertions read from the same objects, then the consolidated canonicals.
    facts, gen, slots = consolidated_facts(village_dir, strict=args.strict)
    profiles = gen.canonical_profiles()
    unions = gen.canonical_unions()
    # Every event comment cites a record: which records name each canonical,
    # in what slot, is the facts layer's answer; the section each was minted
    # with is the translator's. Nothing is cut out of the joined `about`.
    appearances = appearances_by_canonical(
        facts, consolidated_identity(gen, slots.object_of),
        section_of=lambda persona: gen.section_minted_for(slots.object_of(persona)))

    persons, marriages = project_kin(
        profiles, unions, kin, resolve=gen.resolve_canonical,
        parent_overrides=parent_overrides, sources_by_res=sources_by_res,
        appearances=appearances,
    )

    header = "# GENERATED by generate_familio_tf.py — DO NOT EDIT.\n\n"
    (output_dir / "familio_persons.tf").write_text(
        header + "".join(p.to_terraform() for p in persons)
    )
    (output_dir / "familio_marriages.tf").write_text(
        header + "".join(m.to_terraform() for m in marriages)
    )
    imports = "".join(p.import_block() for p in persons if p.uuid)
    (output_dir / "familio_imports.tf").write_text(header + imports)
    # Settlement UUIDs live in one `locals` block; person place fields reference
    # them as `local.settlement_*` (set DRY, single source of the opaque ids).
    (output_dir / "familio_locals.tf").write_text(header + settlement_locals_hcl())

    n_import = sum(1 for p in persons if p.uuid)
    print(
        f"familio: {len(persons)} persons ({n_import} import / "
        f"{len(persons) - n_import} create), {len(marriages)} marriages "
        f"→ {output_dir}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
