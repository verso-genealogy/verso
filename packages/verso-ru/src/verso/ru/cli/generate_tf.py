"""Generate terraform `.tf` files for a village from its DSL Python records.

Usage:
    python generate_tf.py --village <Name> [--year YYYY] [--output-dir <path>]

Consumes the typed DSL records (BirthRecords / MarriageRecords / DeathRecords /
CensusRecords) defined under `<village>/YYYY/*.py` and emits Geni's terraform resources.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

from verso.ru import corpus_data
from verso.core.pipeline.config import consolidation_state_blocks, village_config
from verso.ru.pipeline.translate import feed_all_records, make_consolidation
from verso.core.targets.geni.fmt import terraform_fmt


_MOVED_BLOCK_RE = re.compile(
    r"moved\s*\{[^{}]*?from\s*=\s*geni_profile\.(?P<frm>\S+)"
    r"[^{}]*?to\s*=\s*geni_profile\.(?P<to>\S+)[^{}]*?\}"
)


def _previous_keepers(previous_content: str) -> dict[str, str]:
    """Map canonical -> the keeper its last generated `moved` block used. The
    committed `_moved_consolidated_profiles.tf` reflects what was APPLIED, so a
    canonical whose keeper differs now is the keeper-pin gotcha (a freshly
    merged record sorted to profile_names[0], in state beside the canonical)."""
    return {
        m.group("to"): m.group("frm")
        for m in _MOVED_BLOCK_RE.finditer(previous_content or "")
    }


def build_moved_consolidated_profiles(
        gcn, previous_content: str = "") -> tuple[str, list[str]]:
    """Render the `_moved_consolidated_profiles.tf` state-continuity blocks
    from `profiles_to_consolidate`. Returns (content, warnings).

    For every target carrying `generate_moved_block: True`:
      * normal target -> one `moved { from = <keeper> to = <canonical> }`
        (keeper = the record whose Geni id survives; defaults to
        `profile_names[0]`, override with `keeper`), plus a
        `removed { lifecycle { destroy = false } }` for every other record.
      * `adopt_external: True` target (canonical adopts a profile managed
        elsewhere via `terraform import`) -> `removed{destroy=false}` for
        every record, no `moved`.

    A `moved` whose `from` is already absent from state is a harmless no-op,
    so emitting blocks for long-applied consolidations is safe. Blocks that
    are NOT derivable from the config (records dropped from the DSL) live in
    the hand-maintained `_moved_manual_profiles.tf`.

    `warnings` flags the keeper-pin gotcha: when an ALREADY-EMITTED canonical
    (present in `previous_content`) gets a new `profile_names[0]` with no
    explicit `keeper`, the generated `moved` would point from a freshly merged
    record — in state beside the canonical — and destroy it on apply. Compared
    against the committed file so the check needs no live state; back it with
    `verso verify-plan` (which catches the destroy itself)."""
    blocks = consolidation_state_blocks(gcn)
    moved = [(b.frm, b.canonical) for b in blocks if b.kind == "moved"]
    removed = [b.frm for b in blocks if b.kind == "removed"]

    prev_keepers = _previous_keepers(previous_content)
    warnings: list[str] = []
    for key, entry in getattr(gcn, "profiles_to_consolidate", {}).items():
        if not isinstance(entry, dict) or not entry.get("generate_moved_block"):
            continue
        names = entry.get("profile_names") or []
        if not names or entry.get("adopt_external"):
            continue
        explicit_keeper = entry.get("keeper")
        keeper = explicit_keeper or names[0]

        old_keeper = prev_keepers.get(key)
        if (not explicit_keeper and old_keeper
                and old_keeper != keeper and old_keeper in names):
            warnings.append(
                f"keeper-pin: consolidation target '{key}' was already applied "
                f"with keeper {old_keeper!r}, but profile_names[0] is now "
                f"{keeper!r}. The generated moved would try to move {keeper!r} "
                f"(merged into '{key}' on Geni, still a separate state entry) "
                f"onto the existing canonical and DESTROY it. Pin "
                f'\'"keeper": "{old_keeper}"\' to keep the moved a no-op '
                "(the keeper rule), or confirm with `verso verify-plan` on a "
                "fresh plan exported to the village's `_plan.json`."
            )

    out = [
        "# GENERATED by generate_tf.py from profiles_to_consolidate — DO NOT EDIT.",
        "# moved: keeper record -> canonical (preserves the surviving Geni id).",
        "# removed{destroy=false}: absorbed duplicates (already merged on Geni).",
        "# Non-derivable exceptions are hand-maintained in _moved_manual_profiles.tf.",
        "",
    ]
    for frm, to in moved:
        out += [f"moved {{\n  from = geni_profile.{frm}\n  to   = geni_profile.{to}\n}}", ""]
    for frm in removed:
        out += [
            f"removed {{\n  from = geni_profile.{frm}\n  lifecycle {{\n    destroy = false\n  }}\n}}",
            "",
        ]
    return "\n".join(out) + "\n", warnings


def strict_failure_hints(skipped: list[tuple[Path, Exception]]) -> list[str]:
    """Recipe lines for the `--strict` abort, keyed on why each file failed.

    The generator raises a bare `ValueError` with no line number, while the DSL
    linters report the SAME problem with a file:line and a code — but nothing
    tells you that, so each occurrence costs a round-trip to rediscover. These
    lines close that gap.
    """
    kinds = set()
    for _path, exc in skipped:
        msg = str(exc).lower()
        if isinstance(exc, ValueError) and ("patronymic" in msg or "name" in msg):
            kinds.add("names")
        elif isinstance(exc, ImportError):  # covers ModuleNotFoundError
            kinds.add("imports")
        else:
            kinds.add("other")

    paths = " ".join(f'"{p}"' for p, _ in skipped)
    hints = ["", "How to fix:"]
    if "names" in kinds:
        hints += [
            "  A name or patronymic is not in the registry. The DSL linter reports the same",
            "  problem WITH a line number, before generation ever runs:",
            f"      verso dsllint {paths}",
            "  Then register the form (names.csv row / names_ignore.csv / patronymics_ignore.csv)",
            "  or move a surname out of the patronymic slot with last_name_orig=;",
            "  `verso names --help` says which of those applies.",
        ]
    if "imports" in kinds:
        hints += [
            "  A file failed to import — usually a status or cause-of-death constant that is",
            "  used but not imported. Check the file's import block, then:",
            f"      .venv/bin/ruff check {paths}",
        ]
    if "other" in kinds:
        hints += [
            "  Unrecognised failure — run the linters on the file(s) for a located error:",
            f"      verso dsllint {paths}",
            f"      .venv/bin/ruff check {paths}",
        ]
    return hints


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--village", required=True)
    parser.add_argument(
        "--year",
        action="append",
        default=[],
        help="Restrict to a specific year. May be repeated, or comma-separated "
             "(e.g. --year 1809 --year 1810, or --year 1809,1810). "
             "When set, only mk_{YEAR}_*.tf files matching the requested "
             "years are written; cross-year baptism records that would land "
             "in another year's file are skipped, and consolidated_*.tf are "
             "left untouched (they need a full-village run for correctness).",
    )
    parser.add_argument("--output-dir")
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Fail (exit 2) if any DSL file is skipped because it failed to "
             "import. Without this, a broken file (e.g. a missing status "
             "import) is only a stderr warning and silently drops all of its "
             "records from the generated output.",
    )
    parser.add_argument(
        "--fail-on-conflicts",
        action="store_true",
        help="Exit 3 if consolidation silently dropped a field value (two "
             "source records disagreeing on last_name, a date, cause_of_death, "
             "etc. with no preference/override/ignore pin). Without this, such "
             "conflicts are only printed to stderr as a warning. Also gates "
             "ROV001 (4) and RIG001 (5), whose backlogs are at zero.",
    )
    parser.add_argument(
        "--fail-on-redundant-config",
        action="store_true",
        help="Exit 6/7 on RPF001 dead preference pins / RAI001 dead "
             "additional_info entries. Deliberately NOT folded into "
             "--fail-on-conflicts: both land with a large pre-existing "
             "backlog in villages not yet swept, so gating CI on "
             "them would turn the build red on work nobody has done yet. "
             "Fold them in once a village reaches zero.",
    )
    args = parser.parse_args(argv)
    years: list[int] = []
    for raw in args.year:
        for part in str(raw).split(","):
            part = part.strip()
            if part:
                years.append(int(part))

    village_dir = Path(args.village)
    output_dir = Path(args.output_dir) if args.output_dir else village_dir / "terraform" / "geni"
    output_dir.mkdir(parents=True, exist_ok=True)

    # Late import so tests can exercise discovery without pulling translator deps.
    from verso.ru.targets.geni.translator import Consolidation, TerraformGenerator
    from verso.core.targets.geni.consolidation_conflicts import (
        exit_code_for_conflicts, format_conflict_report)
    from verso.core.targets.geni.redundant_ignores import (
        exit_code_for_redundant_ignores, format_redundant_ignore_report)
    from verso.core.targets.geni.redundant_additional_info import (
        exit_code_for_redundant_additional_info, format_redundant_additional_info_report)
    from verso.core.targets.geni.redundant_overrides import (
        exit_code_for_redundant_overrides, format_redundant_override_report)
    from verso.core.targets.geni.redundant_preferences import (
        exit_code_for_redundant_preferences, format_redundant_preference_report)

    consolidation = Consolidation()
    moved_profiles_content: str | None = None
    gcn_module: Any = None
    gcn = village_config(village_dir)
    if gcn is not None:
        gcn_module = gcn
        prev_moved = output_dir / "_moved_consolidated_profiles.tf"
        prev_content = (
            prev_moved.read_text(encoding="utf-8") if prev_moved.exists() else "")
        moved_profiles_content, keeper_warnings = build_moved_consolidated_profiles(
            gcn, prev_content)
        for w in keeper_warnings:
            print(f"warning: {w}", file=sys.stderr)
        consolidation = make_consolidation(gcn)

    settings = corpus_data.village(village_dir)
    gen = TerraformGenerator(
        village_dir=str(village_dir),
        consolidation=consolidation,
        projects=list(settings.projects),
        extra_project_rules=dict(settings.project_rules),
        prev_revision=settings.prev_revision,
    )
    skipped: list[tuple[Path, Exception]] = []
    feed_all_records(gen, village_dir, years, skipped)

    # Strict guard: a file that failed to import contributed no records, so
    # the consolidated_*.tf would be written WITHOUT them — a silent data
    # drop. Abort before writing rather than emit a corrupted tree.
    if args.strict and skipped:
        print(
            f"\nerror: --strict: {len(skipped)} DSL file(s) skipped due to "
            f"import failure (their records are missing from the output):",
            file=sys.stderr,
        )
        for path, exc in skipped:
            print(f"  - {path}: {type(exc).__name__}: {exc}", file=sys.stderr)
        for line in strict_failure_hints(skipped):
            print(line, file=sys.stderr)
        return 2

    gen.finalize()

    # Surface any field value the consolidation merge silently dropped. Warn
    # by default (CI stays green); `--fail-on-conflicts` turns it into a
    # non-zero exit. Output is still written either way — conflicts don't
    # corrupt the tree, they just lose a datum.
    # The suggested pins leave out what RPF001 below would call dead.
    conflict_report = format_conflict_report(
        gen.consolidation_conflicts, pin_is_dead=gen.preference_pin_is_dead)
    if conflict_report:
        print(conflict_report, file=sys.stderr)

    # ROV001: override fields that set a value the profile already had AND
    # silence no conflict. Same warn-by-default / `--fail-on-conflicts`-blocks
    # contract as consolidation conflicts. Output is still written either way.
    redundant_report = format_redundant_override_report(gen.redundant_overrides)
    if redundant_report:
        print(redundant_report, file=sys.stderr)

    # RIG001: ignore entries whose predicate never matched anything. Same
    # warn-by-default / `--fail-on-conflicts`-blocks contract.
    ignore_report = format_redundant_ignore_report(gen.redundant_ignores)
    if ignore_report:
        print(ignore_report, file=sys.stderr)

    # RPF001: preference pins that never changed what the profile renders.
    # Same warn-by-default / `--fail-on-conflicts`-blocks contract.
    preference_report = format_redundant_preference_report(
        gen.redundant_preferences)
    if preference_report:
        print(preference_report, file=sys.stderr)

    # RAI001: additional_info entries whose merge changed nothing. Same
    # warn-by-default / `--fail-on-conflicts`-blocks contract.
    additional_info_report = format_redundant_additional_info_report(
        gen.redundant_additional_info)
    if additional_info_report:
        print(additional_info_report, file=sys.stderr)

    # CST001/CST002: a config entry naming a res_name the DSL no longer
    # produces. It folds NOTHING, so the duplicate it was written to remove is
    # standing in the tree this command has just written — and the tree looks
    # fine, which is how it went unnoticed twice in one session. The check is
    # free here (the translation it needs is the one above), where running it
    # as a separate target costs a second full translation. Warn only: CI
    # already fails on new entries, and pre-existing debt sits in the village
    # baseline.
    if gcn_module is not None and not years:
        from verso.ru.consolidation.stale_stubs import (
            findings_for, format_report, load_baseline)
        stale = findings_for(gcn_module, gen.consolidation)
        baseline = load_baseline(str(village_dir))
        new_stale = [f for f in stale if f.ref not in baseline]
        report = format_report(str(village_dir.name), new_stale,
                               len(stale) - len(new_stale))
        if report:
            print(report, file=sys.stderr)

    # When restricted to specific years, only write files belonging to those
    # years. Skip cross-year overflow into adjacent years (those would
    # truncate the adjacent year's file with a partial slice) and skip the
    # corpus-wide consolidated_*.tf files (they need a full-village run).
    import re as _re
    # Per-year file families: mk_YYYY_*.tf / rs_YYYY_*.tf (trailing "_") and
    # ext_YYYY.tf / list_YYYY.tf (year immediately before ".tf"). The trailing
    # `[_.]` matches both shapes so a `--year` run writes external-source and
    # name-list files too (not just metric-book / census).
    year_re = _re.compile(r"^(?:mk|rs|ext|list)_(\d{4})[_.]")
    emitted: set[str] = set()
    for filename, content in gen.iter_outputs():
        if years:
            m = year_re.match(filename)
            if not m or int(m.group(1)) not in set(years):
                continue
        (output_dir / filename).write_text(content)
        emitted.add(filename)

    # Drop stale `consolidated_profiles_*.tf` shards from previous runs.
    # The translator's alphabetical chunking may produce fewer shards than
    # a previous run did; leftover shards would duplicate resources.
    if not years:
        for stale in output_dir.glob("consolidated_profiles_*.tf"):
            if stale.name not in emitted:
                stale.unlink()

        # Drop stale per-year `mk_*`/`rs_*` files whose year no longer emits
        # any content — e.g. a year re-transcribed with every record
        # `reviewed=False` produces no profiles/documents, so the generator
        # writes nothing for it. Without cleanup the previous run's file
        # lingers as an orphan, referencing profiles that are no longer
        # emitted (undeclared-resource errors on `terraform validate`).
        # Full runs only: a `--year` run intentionally leaves other years'
        # files untouched, so it must not delete them.
        for stale in (*output_dir.glob("mk_*.tf"), *output_dir.glob("rs_*.tf")):
            if year_re.match(stale.name) and stale.name not in emitted:
                stale.unlink()

        # State-continuity blocks for consolidated profiles (full runs only —
        # these are corpus-wide, like the consolidated_*.tf shards).
        if moved_profiles_content is not None:
            (output_dir / "_moved_consolidated_profiles.tf").write_text(
                moved_profiles_content
            )

    # Format the emitted .tf so EVERY invocation leaves fmt-clean output. The
    # Makefile's tf-generate fmts too, but a raw `python -m verso.ru.cli.generate_tf`
    # (or the --year-scoped path) would otherwise skip it and trip CI's
    # `terraform fmt -check`. Best-effort: skipped if terraform isn't on PATH.
    _terraform_fmt(output_dir)

    # Conflicts (3) take precedence over ROV001 (4) over RIG001 (5) over
    # RPF001 (6) over RAI001 (7), so a code anything already keys on keeps
    # its meaning. The last two answer to their own flag — see
    # `--fail-on-redundant-config`.
    return (
        exit_code_for_conflicts(
            gen.consolidation_conflicts,
            fail_on_conflicts=args.fail_on_conflicts,
        )
        or exit_code_for_redundant_overrides(
            gen.redundant_overrides,
            fail_on_conflicts=args.fail_on_conflicts,
        )
        or exit_code_for_redundant_ignores(
            gen.redundant_ignores,
            fail_on_conflicts=args.fail_on_conflicts,
        )
        or exit_code_for_redundant_preferences(
            gen.redundant_preferences,
            fail_on_conflicts=args.fail_on_redundant_config,
        )
        or exit_code_for_redundant_additional_info(
            gen.redundant_additional_info,
            fail_on_conflicts=args.fail_on_redundant_config,
        )
    )


def _terraform_fmt(output_dir: Path) -> None:
    """`terraform fmt -recursive` on the generated dir, its files in parallel groups; best-effort."""
    terraform_fmt(output_dir, recursive=True)


if __name__ == "__main__":
    sys.exit(main())
