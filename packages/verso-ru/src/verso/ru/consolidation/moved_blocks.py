#!/usr/bin/env python3
"""Turn a plan's rename-induced destroy+create pairs into `moved {}` blocks.

On an ALREADY-APPLIED village a res_name rename is DESTRUCTIVE: terraform destroys
the live geni_profile and creates a new one, losing its Geni id and everything
hanging off it (merges, curator edits, relationships). A `moved {}` block renames
it in state instead.

Pairs deletes with creates WITHIN a record, then tiers them:

  AUTO     — certainly the same person; written to _moved_auto_renames.tf
  REVIEW   — plausibly the same person, but the given name / patronymic changed, or
             the role moved; PRINTED for human sign-off, never written
  UNPAIRED — a delete with no create in its record: a REAL destroy

The tiering is the whole point. In a birth record whose mis-read "father" turned
out to be a godparent, the same man — so moving him was right — while the father
SLOT came to hold a different man entirely. Auto-writing that second pair would
have rebranded a live Geni profile onto another human. Pairing alone cannot tell
those apart, so anything ambiguous is printed, never written.

Pure and network-free (reads the plan JSON only), like verify_plan.

Usage:
  python3 -m verso.ru.consolidation.moved_blocks --village Маниловка
  python3 -m verso.ru.consolidation.moved_blocks --village Маниловка --dry-run
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from verso.ru.consolidation.plan import plan_command, plan_paths

# The tool OWNS this file and rewrites it wholesale. It must never touch
# `_moved_renames.tf` (a hand-maintained rename audit trail in Горюхино) or
# `_moved_manual_profiles.tf` (hand-written) — both would be clobbered.
AUTO_FILE = "_moved_auto_renames.tf"

_HEADER = """\
# GENERATED by `verso moved-blocks` — DO NOT EDIT.
#
# State continuity for res_name renames on an APPLIED village. Without these,
# terraform DESTROYS the live Geni profile and creates a new one, losing its id.
#
# Only UNAMBIGUOUS renames land here (same person, same record, surname-only
# change). Anything needing judgement — a role change, or a changed given
# name/patronymic — is printed for review and belongs in the hand-maintained
# _moved_manual_profiles.tf.
"""

# The role vocabulary, taken from the real trees (not invented): god_parent_N,
# child, witness_N, father, deceased, bride, groom, relative, mother, rel_N,
# bride_relative[_N], groom_relative_N, groom_father. Longest alternatives first
# so `bride_relative_1` does not match bare `bride`.
ROLE = (
    r"god_parent_\d+|groom_relative_\d+|bride_relative_\d+|bride_relative"
    r"|groom_father|witness_\d+|rel_\d+"
    r"|father|mother|child|groom|bride|relative|deceased"
)
# The date is NOT always a full YYYY_MM_DD: the real trees carry partial dates
# (`_1799_11_ivan_...` — year+month, no day) and the name can be entirely absent
# (`_1784_06_06_mk_deaths_4_deceased` — an unnamed deceased). Validated against all
# 31k per-record profiles; anchoring on YYYY_MM_DD alone missed 94 of them, which
# would then have been misreported as real destroys.
_PREFIX = re.compile(r"^_(\d{4}(?:_\d{1,2})*)_?(.*)$")
# <kind>_<num>_<role>[_<uniq>] — num is non-greedy so `29_god_parent_2` parses as
# num=29 role=god_parent_2, and `6_father_2` as num=6 role=father uniq=2.
_SUFFIX = re.compile(rf"^(births|marriages|deaths)_(.+?)_({ROLE})(?:_(\d+))?$")
# Census (`_rs_`) names have no record-kind word: `<family>_<member>_<role>`,
# e.g. `17_7_family_member`. The family+member pair IS the slot, so it becomes
# `num` and two profiles in the same slot pair as the same person.
CENSUS_ROLE = r"family_member|head_of_family"
_SUFFIX_RS = re.compile(rf"^(.+?)_({CENSUS_ROLE})(?:_(.+))?$")
# Name-list (`_list_`) names: `<entry №>_listed`, e.g. `449_listed`. The entry
# number is the slot, as a двор+member pair is on a roll. A village holds one
# list per year, so (year, "list", №) names one line of one document.
_SUFFIX_LIST = re.compile(r"^(.+?)_(listed)(?:_(.+))?$")

@dataclass(frozen=True)
class ResName:
    date: str
    name: str
    kind: str
    num: str
    role: str
    uniq: str | None

    @property
    def record(self) -> tuple[str, str, str]:
        """The record this profile belongs to: (year, kind, №).

        Deliberately NOT the full date: a record's date can be CORRECTED (a birth
        moved from 06-05 to 11-05) while remaining the same record. Keying on
        the date would fail to pair those and report them as real destroys.
        """
        return (self.date[:4], self.kind, self.num)


@dataclass(frozen=True)
class Pair:
    rtype: str
    old: str
    new: str
    geni_id: str
    tier: str   # "auto" | "review"
    why: str


def parse_profile(res: str) -> ResName | None:
    """Parse a per-record geni_profile res_name. None if it is not one."""
    head, sep, tail = res.partition("_mk_")
    if sep:
        m_head = _PREFIX.match(head)
        m_tail = _SUFFIX.match(tail)
        if not (m_head and m_tail):
            return None
        return ResName(
            date=m_head.group(1),
            name=m_head.group(2),
            kind=m_tail.group(1),
            num=m_tail.group(2),
            role=m_tail.group(3),
            uniq=m_tail.group(4),
        )
    # Census revision names. Without this a census rename cannot pair at all and
    # every one is reported as a real destroy (46 such profiles across Нижняя
    # Яичница and Маниловка when daughters' res_names gained their maiden surname).
    # Name-list entries likewise: a name list, read against the scan after it
    # was applied, renamed live entries (one surname re-read as a near-homograph)
    # whose moved blocks then had to be written by hand.
    for token, suffix, kind in (("_rs_", _SUFFIX_RS, "rs"),
                                ("_list_", _SUFFIX_LIST, "list")):
        head, sep, tail = res.partition(token)
        if not sep:
            continue
        m_head = _PREFIX.match(head)
        m_tail = suffix.match(tail)
        if not (m_head and m_tail):
            return None
        return ResName(
            date=m_head.group(1),
            name=m_head.group(2),
            kind=kind,
            num=m_tail.group(1),
            role=m_tail.group(2),
            uniq=m_tail.group(3),
        )
    return None


def _actions(rc: dict[str, Any]) -> list[str]:
    return (rc.get("change") or {}).get("actions") or []


def _surname_only_change(old: str, new: str) -> bool:
    """True when the given name AND patronymic are unchanged — i.e. only the surname
    (or its spelling) moved.

    A changed GIVEN NAME is indistinguishable from an identity swap by pairing alone,
    which is precisely the trap of two births renumbered in one book. So `zaha`->`zahar` and ''->'matrona' are
    NOT surname-only; they go to review.
    """
    o, n = old.split("_"), new.split("_")
    if len(o) < 2 or len(n) < 2:
        return False
    return o[0] == n[0] and o[1] == n[1]


def pair_profiles(plan: dict[str, Any]) -> tuple[list[Pair], list[tuple[str, str]]]:
    """Pair geni_profile deletes with creates inside the same record.

    Returns (pairs, unpaired) where unpaired is [(res_name, geni_id)] — deletes with
    no create in their record, i.e. REAL destroys.

    Note a delete+create on the SAME address is a force-replace, not a rename, and is
    ignored here: only pure deletes and pure creates take part.
    """
    dels: dict[str, str] = {}
    crts: list[str] = []
    for rc in plan.get("resource_changes") or []:
        if rc.get("type") != "geni_profile":
            continue
        name = rc["address"].split(".", 1)[1]
        acts = _actions(rc)
        if acts == ["delete"]:
            dels[name] = ((rc["change"].get("before") or {}).get("id")) or ""
        elif acts == ["create"]:
            crts.append(name)

    by_record: dict[tuple[str, str, str], list[str]] = defaultdict(list)
    for c in crts:
        p = parse_profile(c)
        if p:
            by_record[p.record].append(c)

    pairs: list[Pair] = []
    unpaired: list[tuple[str, str]] = []
    used: set[str] = set()

    parsed: list[tuple[str, ResName]] = []
    for name in sorted(dels):
        p = parse_profile(name)
        if p is None:
            # ext_ cards: no record to pair within. Never guess — report.
            unpaired.append((name, dels[name]))
        else:
            parsed.append((name, p))

    # Pass A — same PERSON name within the record (the role may have moved).
    still: list[tuple[str, ResName]] = []
    for name, p in parsed:
        hit = None
        for c in by_record[p.record]:
            q = parse_profile(c)
            if c not in used and q and q.name == p.name:
                hit = c
                break
        if hit is None:
            still.append((name, p))
            continue
        used.add(hit)
        q = parse_profile(hit)
        assert q is not None
        same_role = q.role == p.role
        pairs.append(Pair(
            "geni_profile", name, hit, dels[name],
            "auto" if same_role else "review",
            "same person, same role" if same_role else "role change",
        ))

    # Pass B — same ROLE within the record (the name changed).
    for name, p in still:
        hit = None
        for c in by_record[p.record]:
            q = parse_profile(c)
            if c not in used and q and q.role == p.role:
                hit = c
                break
        if hit is None:
            unpaired.append((name, dels[name]))
            continue
        used.add(hit)
        q = parse_profile(hit)
        assert q is not None
        surname_only = _surname_only_change(p.name, q.name)
        pairs.append(Pair(
            "geni_profile", name, hit, dels[name],
            "auto" if surname_only else "review",
            "surname spelling" if surname_only
            else "given name / patronymic changed",
        ))

    return pairs, unpaired


def render(pairs: list[Pair]) -> str:
    """The `_moved_auto_renames.tf` body — AUTO pairs only, never review."""
    out = [_HEADER]
    for p in sorted(pairs, key=lambda x: (x.rtype, x.old)):
        if p.tier != "auto":
            continue
        out.append(
            f"\n# {p.geni_id}\n"
            f"moved {{\n"
            f"  from = {p.rtype}.{p.old}\n"
            f"  to   = {p.rtype}.{p.new}\n"
            f"}}\n"
        )
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Generate moved{} blocks for res_name renames in a plan.")
    ap.add_argument("--village", default=None)
    ap.add_argument("--plan", default=None, help="plan JSON path")
    ap.add_argument("--dry-run", action="store_true",
                    help="print everything, write nothing")
    args = ap.parse_args(argv)

    paths = plan_paths(args.village)
    plan = (json.loads(Path(args.plan).read_text(encoding="utf-8"))
            if args.plan else paths.load_json())

    pairs, unpaired = pair_profiles(plan)
    auto = [p for p in pairs if p.tier == "auto"]
    review = [p for p in pairs if p.tier == "review"]

    if review:
        print(f"\nREVIEW ({len(review)}) — confirm each is the SAME PERSON, then paste "
              f"into _moved_manual_profiles.tf:\n")
        for p in review:
            print(f"  [{p.why}] {p.geni_id}")
            print(f"    - {p.old}")
            print(f"    + {p.new}")
            print(f"    moved {{ from = {p.rtype}.{p.old}  to = {p.rtype}.{p.new} }}\n")

    if unpaired:
        print(f"\nUNPAIRED DELETES ({len(unpaired)}) — these WILL be destroyed on "
              f"apply:\n")
        for name, gid in unpaired:
            print(f"  {gid}  {name}")

    if not auto:
        print("\nAUTO (0) — nothing to write.")
        return 0

    if args.dry_run:
        print(f"\nAUTO ({len(auto)}) — would write to {AUTO_FILE}:\n")
        print(render(pairs))
        return 0

    target = paths.tf_dir / AUTO_FILE
    target.write_text(render(pairs), encoding="utf-8")
    print(f"\nAUTO ({len(auto)}) — wrote {target}")
    print("Re-plan to confirm the destroys are gone:")
    print(f'  {plan_command(paths.village_dir)}')
    return 0


if __name__ == "__main__":
    sys.exit(main())
