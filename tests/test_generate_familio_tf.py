"""Tests for verso.ru.cli.generate_familio_tf — the familio TF generator CLI."""

import tempfile
import textwrap
import unittest
from pathlib import Path

from verso.ru.cli.generate_familio_tf import load_kin, main as familio_main
from verso.ru.pipeline.translate import translate_village
from verso.ru.familio.projection import KinResolutionError


def _make_village(td: str) -> Path:
    """A minimal synthetic village: one birth record with father + mother,
    so the translation yields three profiles and one parents' union."""
    village = Path(td) / "Тестовка"
    year = village / "1800"
    year.mkdir(parents=True)
    (year / "test_births_1800.py").write_text(textwrap.dedent('''
        from calendar import Month
        from verso.ru.dsl import birth, birth_month, birth_records
        from verso.ru.dsl import Gender, person

        test_births_1800 = birth_records(
            "A", "1", "1", "1", "Тестовка", "N", 1800,
            *birth_month(Month.MARCH,
                birth(1, Gender.MALE, 10, 11,
                      child=person("Иван"),
                      father=person("Петр", "Сидоров"),
                      mother=person("Марья", "Петрова"))),
        )
    '''))
    return village


def _family_res_names(village: Path) -> tuple[str, str, str]:
    """Resolve the (father, mother, child) canonical res_names the
    translation actually mints, so the tests don't guess transliterations."""
    gen, _ = translate_village(village, strict=True)
    profiles = gen.canonical_profiles()
    father = next(r for r in profiles if r.endswith("_father"))
    mother = next(r for r in profiles if r.endswith("_mother"))
    child = next(r for r in profiles if r.endswith("_child"))
    return father, mother, child


class TestLoadKin(unittest.TestCase):
    def test_missing_registry_errors_loudly(self):
        with tempfile.TemporaryDirectory() as td:
            with self.assertRaises(FileNotFoundError):
                load_kin(Path(td))

    def test_kin_must_be_a_dict(self):
        with tempfile.TemporaryDirectory() as td:
            (Path(td) / "familio_kin.py").write_text('KIN = ["not", "a", "dict"]\n')
            with self.assertRaises(TypeError):
                load_kin(Path(td))

    def test_optional_maps_default_empty(self):
        with tempfile.TemporaryDirectory() as td:
            (Path(td) / "familio_kin.py").write_text('KIN = {"a_res_name": None}\n')
            kin, overrides, sources = load_kin(Path(td))
            self.assertEqual(kin, {"a_res_name": None})
            self.assertEqual(overrides, {})
            self.assertEqual(sources, {})

    def test_parent_overrides_are_returned(self):
        with tempfile.TemporaryDirectory() as td:
            (Path(td) / "familio_kin.py").write_text(textwrap.dedent('''
                KIN = {"child_res": None}
                PARENT_OVERRIDES = {"child_res": ("father_res",)}
            '''))
            _kin, overrides, _sources = load_kin(Path(td))
            self.assertEqual(overrides, {"child_res": ("father_res",)})


class TestGenerateFamilioTfCli(unittest.TestCase):
    def test_end_to_end_generates_all_four_tf_files(self):
        with tempfile.TemporaryDirectory() as td:
            village = _make_village(td)
            father, mother, child = _family_res_names(village)
            (village / "familio_kin.py").write_text(textwrap.dedent(f'''
                KIN = {{
                    {father!r}: "00000000-0000-0000-0000-000000000001",
                    {mother!r}: None,
                    {child!r}: None,
                }}
            '''))
            out = Path(td) / "out"

            rc = familio_main(["--village", str(village), "--strict",
                               "--output-dir", str(out)])
            self.assertEqual(rc, 0)

            persons_tf = (out / "familio_persons.tf").read_text()
            marriages_tf = (out / "familio_marriages.tf").read_text()
            imports_tf = (out / "familio_imports.tf").read_text()
            locals_tf = (out / "familio_locals.tf").read_text()

            # Every generated file carries the DO NOT EDIT header.
            for text in (persons_tf, marriages_tf, imports_tf, locals_tf):
                self.assertIn("GENERATED by generate_familio_tf.py", text)

            # Three kin → three familio_person resources.
            self.assertEqual(persons_tf.count('resource "familio_person"'), 3)
            # Both parents are kin → their union projects as one marriage.
            self.assertEqual(marriages_tf.count('resource "familio_marriage"'), 1)
            # Exactly the UUID'd kin gets an import block.
            self.assertEqual(imports_tf.count("import {"), 1)
            self.assertIn("00000000-0000-0000-0000-000000000001", imports_tf)

    def test_event_comments_cite_the_persons_own_records(self):
        """End to end, through the facts bridge and the translator's sections:
        a burial reaches the death comment. It is headed «умерший», and the
        role-word regex the projection used to cut the about with looked for
        «смерт» — 61 kin across five villages had no death comment."""
        with tempfile.TemporaryDirectory() as td:
            village = _make_village(td)
            (village / "1800" / "test_deaths_1800.py").write_text(textwrap.dedent('''
                from calendar import Month
                from verso.ru.dsl import death, death_month, death_records
                from verso.ru.dsl import Gender, person

                test_deaths_1800 = death_records(
                    "A", "1", "1", "1", "Тестовка", "N", 1800,
                    *death_month(Month.MAY,
                        death(1, Gender.MALE, 3, 4,
                              deceased=person("Петр", "Сидоров"), age=40)),
                )
            '''))
            gen, _ = translate_village(village, strict=True)
            profiles = gen.canonical_profiles()
            child = next(r for r in profiles if r.endswith("_child"))
            dead = next(r for r in profiles if r.endswith("_deceased"))
            (village / "familio_kin.py").write_text(
                f"KIN = {{{child!r}: None, {dead!r}: None}}\n")
            out = Path(td) / "out"
            self.assertEqual(0, familio_main(["--village", str(village), "--strict",
                                              "--output-dir", str(out)]))
            persons_tf = (out / "familio_persons.tf").read_text()

            def block(res: str) -> str:
                return persons_tf.split(f'resource "familio_person" "{res}"')[1] \
                    .split('resource "familio_person"')[0]
            death = block(dead).split("death = {")[1]
            self.assertIn("МК Тестовка 1800: умерший", death)
            # the age at death is an indirect birth source too
            self.assertIn("МК Тестовка 1800: умерший", block(dead).split("birth = {")[1])
            self.assertIn("МК Тестовка 1800", block(child).split("birth = {")[1])

    def test_a_wedding_appearance_knows_the_spouse_and_the_parents_child(self):
        """Through the facts bridge: the groom's appearance names the bride's
        canonical as his spouse, and the father's names the groom as his
        child — what lets a marriage comment tell the couple's own wedding
        from another one and from a child's."""
        from verso.ru.pipeline.facts import consolidated_facts
        from verso.ru.facts.projection import consolidated_identity
        from verso.ru.familio.sources import appearances_by_canonical
        with tempfile.TemporaryDirectory() as td:
            village = _make_village(td)
            (village / "1800" / "test_marriages_1800.py").write_text(textwrap.dedent('''
                from calendar import Month
                from verso.ru.dsl import person
                from verso.ru.dsl import marriage, marriage_month, marriage_records
                from verso.ru.dsl import Relationship, relative

                test_marriages_1800 = marriage_records(
                    "A", "1", "1", "1", "Тестовка", "N", 1800,
                    *marriage_month(Month.MAY,
                        marriage(1, 11,
                                 groom=person("Иван", "Петров", "Сидоров"), groom_age=20,
                                 bride=person("Анна", "Павлова"), bride_age=18,
                                 relatives=[relative(person("Петр", "Сидоров"),
                                                     Relationship.FATHER, "жених")])),
                )
            '''))
            facts, gen, slots = consolidated_facts(village, strict=True)
            appearances = appearances_by_canonical(
                facts, consolidated_identity(gen, slots.object_of),
                section_of=lambda p: gen.section_minted_for(slots.object_of(p)))
            wedding = {a.slot: (res, a) for res, apps in appearances.items()
                       for a in apps if a.kind == "marriage"}
            groom_res, groom = wedding["groom"]
            bride_res, _ = wedding["bride"]
            _, father = wedding["relative1"]
            self.assertEqual(bride_res, groom.spouse)
            self.assertEqual(frozenset({groom_res}), father.weds_children)
            self.assertEqual(groom.record, father.record)

    def test_unknown_kin_res_name_fails(self):
        with tempfile.TemporaryDirectory() as td:
            village = _make_village(td)
            (village / "familio_kin.py").write_text(
                'KIN = {"nobody_of_that_name_1800": None}\n')
            out = Path(td) / "out"
            with self.assertRaises(KinResolutionError):
                familio_main(["--village", str(village), "--strict",
                              "--output-dir", str(out)])


if __name__ == "__main__":
    unittest.main()
