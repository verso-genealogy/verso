"""`Person.status_defaulted`: the breadcrumb `RecordDefaults` leaves.

A book's defaults fill an empty status in place. That value may be the scribe's
own repeated wording hoisted by the author, or the author's assumption about the
parish, and nothing about one person tells which — so the facts layer marks it
`Stated(basis_unknown=True)`. It can only do that if the fill leaves a trace.
No generated byte depends on it: the translator never reads the flag.
"""
from __future__ import annotations

import unittest

from verso.ru.domain import Gender, RecordDefaults, person
from verso.ru.domain.statuses import (
    YASAK_PEASANT_FEMALE, YASAK_PEASANT_MALE)
from verso.ru.dsl.records.births import birth, birth_records
from verso.ru.dsl.records.marriages import marriage, marriage_records


class TheFillLeavesATrace(unittest.TestCase):
    def test_a_passed_status_is_not_defaulted(self):
        p = person("Пётр", status=YASAK_PEASANT_MALE)
        RecordDefaults(status_male=YASAK_PEASANT_MALE).apply_to_person(p)
        self.assertFalse(p.status_defaulted)

    def test_a_filled_status_is(self):
        p = person("Пётр")
        RecordDefaults(status_male=YASAK_PEASANT_MALE).apply_to_person(p)
        self.assertEqual(YASAK_PEASANT_MALE, p.status)
        self.assertTrue(p.status_defaulted)

    def test_no_default_leaves_nothing_to_mark(self):
        p = person("Пётр")
        RecordDefaults(residence="Горюхино").apply_to_person(p)
        self.assertIsNone(p.status)
        self.assertFalse(p.status_defaulted)

    def test_the_mother_default_of_a_birth_book(self):
        r = birth_records(
            "a", "f", "i", "c", "Горюхино", "Ц", 1830,
            birth(1, Gender.MALE, child=person("Иван"),
                  father=person("Пётр", status=YASAK_PEASANT_MALE),
                  mother=person("Анна")),
            defaults=RecordDefaults(status_mother=YASAK_PEASANT_FEMALE))
        b = r.records[0]
        assert b.mother is not None and b.father is not None
        self.assertTrue(b.mother.status_defaulted)
        self.assertFalse(b.father.status_defaulted)

    def test_the_groom_and_bride_defaults_of_a_marriage_book(self):
        r = marriage_records(
            "a", "f", "i", "c", "Горюхино", "Ц", 1830,
            marriage(1, groom=person("Иван"), bride=person("Анна")),
            defaults=RecordDefaults(status_groom=YASAK_PEASANT_MALE,
                                    status_bride=YASAK_PEASANT_FEMALE))
        m = r.records[0]
        assert m.groom is not None and m.bride is not None
        self.assertTrue(m.groom.status_defaulted)
        self.assertTrue(m.bride.status_defaulted)


if __name__ == "__main__":
    unittest.main()
